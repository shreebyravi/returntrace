"""Bundle data/, policies/ and recorded runs into app/data.js so index.html works when double-clicked.
Run: python scripts/build_data.py"""
import csv, glob, json, os

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))


def rows(name):
    with open(os.path.join(ROOT, "data", name), encoding="utf-8") as f:
        return list(csv.DictReader(f))


def texts(pattern):
    out = {}
    for p in sorted(glob.glob(os.path.join(ROOT, pattern))):
        out[os.path.splitext(os.path.basename(p))[0]] = open(p, encoding="utf-8").read()
    return out


def jsons(pattern):
    return {os.path.splitext(os.path.basename(p))[0]: json.load(open(p, encoding="utf-8")) for p in sorted(glob.glob(os.path.join(ROOT, pattern)))}


def runs(folder):
    out = {}
    for p in sorted(glob.glob(os.path.join(ROOT, "data", "recorded", folder, "*.jsonl"))):
        out[os.path.splitext(os.path.basename(p))[0]] = [json.loads(l) for l in open(p, encoding="utf-8") if l.strip()]
    return out


meta_path = os.path.join(ROOT, "data", "recorded", "meta.json")
data = {
    "orders": rows("orders.csv"), "returns": rows("returns.csv"), "courier_events": rows("courier_events.csv"),
    "inspections": rows("inspections.csv"), "evidence": rows("evidence.csv"), "messages": rows("messages.csv"),
    "eval_cases": rows("eval_cases.csv"), "ground_truth": json.load(open(os.path.join(ROOT, "data", "ground_truth.json"), encoding="utf-8")),
    "policies": texts("policies/*.md"), "stress": jsons("data/stress/*.json"),
    "recorded": runs("runs"), "before_fix": runs("before-fix"),
    "recorded_meta": json.load(open(meta_path, encoding="utf-8")) if os.path.exists(meta_path) else {},
}
js = "/* Generated by scripts/build_data.py. Do not edit by hand. All data is synthetic. */\n"
js += "var RT_DATA = " + json.dumps(data, ensure_ascii=False, indent=1) + ";\n"
js += "if (typeof module !== 'undefined' && module.exports) module.exports = RT_DATA;\n"
open(os.path.join(ROOT, "app", "data.js"), "w", encoding="utf-8").write(js)
print("app/data.js:", len(data["returns"]), "returns,", len(data["recorded"]), "recorded runs,", len(data["before_fix"]), "before-fix runs")
